-- =========================
-- Security / Auth tables
-- =========================
CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name VARCHAR(255) NOT NULL,

    CONSTRAINT pk_roles      PRIMARY KEY (id),
    CONSTRAINT uq_roles_name UNIQUE (name)
);

-- CREATE INDEX idx_roles_name ON roles (name); -- not needed because postgresql automatically creates a hidden backing index for every PRIMARY KEY and UNIQUE constraint

CREATE TABLE capabilities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255) NULL,

    CONSTRAINT pk_capabilities      PRIMARY KEY (id),
    CONSTRAINT uq_capabilities_name UNIQUE (name)
);

-- CREATE INDEX idx_capabilities_name ON capabilities (name); -- not needed because postgresql automatically creates a hidden backing index for every PRIMARY KEY and UNIQUE constraint

CREATE TABLE roles_capabilities (
    role_id       BIGINT NOT NULL,
    capability_id BIGINT NOT NULL,

    CONSTRAINT pk_roles_capabilities PRIMARY KEY (role_id, capability_id),
    CONSTRAINT fk_roles_capabilities_roles
        FOREIGN KEY (role_id) REFERENCES roles (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_roles_capabilities_capabilities
        FOREIGN KEY (capability_id) REFERENCES capabilities (id)
        ON DELETE CASCADE
);

CREATE INDEX idx_roles_capabilities_capability_id ON roles_capabilities (capability_id);

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    uuid       UUID         NOT NULL,
    username   VARCHAR(255) NOT NULL,
    password   VARCHAR(255) NOT NULL,
    role_id    BIGINT       NOT NULL,

    created_at TIMESTAMPTZ  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    deleted    BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ  NULL,

    CONSTRAINT pk_users          PRIMARY KEY (id),
    CONSTRAINT uq_users_uuid     UNIQUE (uuid),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT fk_users_roles
        FOREIGN KEY (role_id) REFERENCES roles (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_users_role_id    ON users (role_id);
CREATE INDEX idx_users_deleted    ON users (deleted);
-- CREATE INDEX idx_users_active_users ON users (id) WHERE deleted = FALSE; -- partial index is perhaps more optimal than the above index if queries frequently look for non-deleted records (and especially if the partial index is composite and also indexes another field with higher cardinality)
CREATE INDEX idx_users_deleted_at ON users (deleted_at);


